-- Chef App schema, ported from server/db/schema.js + server/db/multitenant.js.
--
-- Column names match the SQLite schema so the JSON API keeps its shape.
-- Type changes (the route DTOs translate where the JSON differs):
--   * ids are BIGINT identity columns (BY DEFAULT, so the SQLite → Postgres
--     data migration can keep existing ids and then reset the sequences)
--   * 0/1 INTEGER flags are BOOLEAN (serialize with serde_util::bool_as_int)
--   * '[]' TEXT columns are JSONB
--   * YYYY-MM-DD columns are DATE, *_at columns are TIMESTAMPTZ
--   * dollar amounts are NUMERIC(12,2); deposit_cents stays integer cents
--
-- Every tenant table carries account_id NOT NULL. Cross-table references
-- between tenant tables are composite foreign keys on (account_id, id), so a
-- row can never point at another account's row even if a route forgets to
-- check ownership (FK checks bypass RLS, so RLS alone would not catch it).

CREATE TABLE accounts (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                   TEXT NOT NULL,
    password_hash           TEXT,
    slug                    TEXT NOT NULL UNIQUE,
    onboarding_completed_at TIMESTAMPTZ,
    last_login_at           TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- SQLite used COLLATE NOCASE; emails are lowercased on the way in as well.
CREATE UNIQUE INDEX accounts_email_lower_key ON accounts (lower(email));

CREATE TABLE settings (
    account_id             BIGINT PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    business_name          TEXT DEFAULT '',
    chef_name              TEXT,
    phone                  TEXT,
    email                  TEXT,
    website                TEXT DEFAULT '',
    location               TEXT DEFAULT '',
    default_session_window NUMERIC(5,2) DEFAULT 3.0,
    default_serving_size   INTEGER DEFAULT 4,
    default_service_fee    NUMERIC(12,2) DEFAULT 0,
    logo_base64            TEXT,
    invoice_prefix         TEXT DEFAULT 'INV',
    deposit_cents          BIGINT DEFAULT 0,
    cancellation_hours     INTEGER DEFAULT 48,
    payment_methods        TEXT DEFAULT '',
    booking_terms          TEXT DEFAULT '',
    response_time_text     TEXT DEFAULT 'within 24 hours',
    service_types          JSONB DEFAULT '[]',
    updated_at             TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE clients (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id        BIGINT NOT NULL REFERENCES accounts(id),
    name              TEXT NOT NULL,
    phone             TEXT,
    email             TEXT,
    address           TEXT,
    household_type    TEXT,
    adults            INTEGER DEFAULT 2,
    children          INTEGER DEFAULT 0,
    serving_size      INTEGER DEFAULT 4,
    allergens         JSONB DEFAULT '[]',
    dietary_styles    JSONB DEFAULT '[]',
    liked_proteins    JSONB DEFAULT '[]',
    disliked_foods    TEXT,
    spice_tolerance   TEXT,
    oven_available    BOOLEAN DEFAULT true,
    stovetop_type     TEXT,
    equipment         JSONB DEFAULT '[]',
    client_containers BOOLEAN DEFAULT false,
    parking_notes     TEXT,
    preferred_day     TEXT,
    preferred_time    TEXT,
    grocery_handling  TEXT,
    chef_notes        TEXT,
    is_active         BOOLEAN DEFAULT true,
    is_sample         BOOLEAN DEFAULT false,
    created_at        TIMESTAMPTZ DEFAULT now(),
    updated_at        TIMESTAMPTZ DEFAULT now(),
    UNIQUE (account_id, id)
);

CREATE TABLE recipes (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id              BIGINT NOT NULL REFERENCES accounts(id),
    name                    TEXT NOT NULL,
    category                TEXT,
    session_fit             TEXT,
    prep_time_min           INTEGER,
    cook_time_min           INTEGER,
    servings_base           INTEGER DEFAULT 4,
    hold_quality            INTEGER,
    reheat_quality          INTEGER,
    key_overlap_ingredients JSONB DEFAULT '[]',
    chef_notes              TEXT,
    raw_instructions        TEXT,
    import_source           TEXT DEFAULT 'manual',
    is_active               BOOLEAN DEFAULT true,
    created_at              TIMESTAMPTZ DEFAULT now(),
    UNIQUE (account_id, id)
);

-- Child of recipes (no account_id; scoped through the parent).
CREATE TABLE ingredients (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id     BIGINT REFERENCES recipes(id) ON DELETE CASCADE,
    name          TEXT NOT NULL,
    qty_4_serving TEXT,
    qty_6_serving TEXT,
    store_section TEXT,
    category      TEXT,
    storage_note  TEXT
);

CREATE TABLE sessions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id           BIGINT NOT NULL REFERENCES accounts(id),
    client_id            BIGINT NOT NULL,
    session_date         DATE,
    -- Free-form time of day as the chef typed it; kept as TEXT.
    session_time         TEXT,
    serving_size         INTEGER DEFAULT 4,
    session_window_hours NUMERIC(5,2) DEFAULT 3.0,
    status               TEXT DEFAULT 'Pending',
    service_fee          NUMERIC(12,2) DEFAULT 0,
    ingredient_cost      NUMERIC(12,2) DEFAULT 0,
    chef_notes           TEXT,
    template_name        TEXT,
    completed_at         TIMESTAMPTZ,
    created_at           TIMESTAMPTZ DEFAULT now(),
    pdf_emailed_at       TIMESTAMPTZ,
    UNIQUE (account_id, id),
    FOREIGN KEY (account_id, client_id) REFERENCES clients(account_id, id)
);

-- Child of sessions.
CREATE TABLE session_dishes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT REFERENCES sessions(id) ON DELETE CASCADE,
    recipe_id  BIGINT REFERENCES recipes(id),
    sort_order INTEGER DEFAULT 0
);

CREATE TABLE session_templates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT NOT NULL REFERENCES accounts(id),
    name        TEXT NOT NULL,
    description TEXT,
    recipe_ids  JSONB DEFAULT '[]',
    is_default  BOOLEAN DEFAULT false,
    created_at  TIMESTAMPTZ DEFAULT now(),
    UNIQUE (account_id, name)
);

-- Child of sessions.
CREATE TABLE grocery_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      BIGINT REFERENCES sessions(id) ON DELETE CASCADE,
    ingredient_name TEXT,
    total_quantity  TEXT,
    store_section   TEXT,
    source_dishes   JSONB DEFAULT '[]',
    is_checked      BOOLEAN DEFAULT false
);

CREATE TABLE recipe_import_log (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id                BIGINT NOT NULL REFERENCES accounts(id),
    recipe_id                 BIGINT,
    import_method             TEXT DEFAULT 'text',
    raw_input_length          INTEGER,
    confidence_score          INTEGER,
    fields_edited_after_parse JSONB DEFAULT '[]',
    created_at                TIMESTAMPTZ DEFAULT now(),
    FOREIGN KEY (account_id, recipe_id) REFERENCES recipes(account_id, id)
);

-- Client intake submissions (public-facing form results)
CREATE TABLE client_intakes (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id             BIGINT NOT NULL REFERENCES accounts(id),
    -- Contact
    name                   TEXT NOT NULL,
    email                  TEXT,
    phone                  TEXT,
    address                TEXT,
    -- Household
    household_type         TEXT,
    adults                 INTEGER DEFAULT 2,
    children               INTEGER DEFAULT 0,
    preferred_serving_size INTEGER DEFAULT 4,
    -- Dietary
    allergens              JSONB DEFAULT '[]',
    dietary_styles         JSONB DEFAULT '[]',
    liked_proteins         JSONB DEFAULT '[]',
    disliked_foods         TEXT,
    spice_tolerance        TEXT,
    cuisine_preferences    TEXT,
    -- Scheduling
    preferred_day          TEXT,
    preferred_time         TEXT,
    scheduling_notes       TEXT,
    -- Kitchen / Service
    kitchen_notes          TEXT,
    client_containers      BOOLEAN DEFAULT true,
    grocery_handling       TEXT DEFAULT 'Client shops',
    number_of_meals        INTEGER,
    -- Notes
    notes_for_chef         TEXT,
    -- Legal
    terms_accepted         BOOLEAN DEFAULT false,
    terms_accepted_at      TIMESTAMPTZ,
    -- Internal tracking
    -- submitted | deposit_pending | deposit_paid | reviewed_by_chef | booked | cancelled
    status                 TEXT DEFAULT 'submitted',
    -- Manual: not_requested | deposit_requested | invoice_sent | payment_pending | paid_offline | waived
    -- Legacy Stripe: unpaid | pending | paid | refunded | failed
    payment_status         TEXT DEFAULT 'not_requested',
    payment_notes          TEXT,
    stripe_session_id      TEXT,
    stripe_payment_intent  TEXT,
    booking_fee_amount     NUMERIC(12,2) DEFAULT 0,
    booking_fee_paid_at    TIMESTAMPTZ,
    pdf_path               TEXT,
    internal_notes         TEXT,
    source                 TEXT DEFAULT 'intake_form',
    -- Conversion tracking
    converted_client_id    BIGINT,
    created_at             TIMESTAMPTZ DEFAULT now(),
    updated_at             TIMESTAMPTZ DEFAULT now(),
    UNIQUE (account_id, id),
    FOREIGN KEY (account_id, converted_client_id) REFERENCES clients(account_id, id)
);

CREATE TABLE invoices (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id         BIGINT NOT NULL REFERENCES accounts(id),
    client_id          BIGINT,
    session_id         BIGINT,
    invoice_number     TEXT,
    -- draft | sent | paid | void
    status             TEXT DEFAULT 'draft',
    issue_date         DATE,
    due_date           DATE,
    client_name        TEXT,
    client_email       TEXT,
    client_address     TEXT,
    client_phone       TEXT,
    business_name      TEXT DEFAULT '',
    chef_name          TEXT,
    chef_email         TEXT,
    chef_phone         TEXT,
    message            TEXT,
    internal_notes     TEXT,
    subtotal           NUMERIC(12,2) DEFAULT 0,
    tax_rate           NUMERIC(7,4) DEFAULT 0,
    tax_amount         NUMERIC(12,2) DEFAULT 0,
    total              NUMERIC(12,2) DEFAULT 0,
    paid_at            TIMESTAMPTZ,
    -- Invoice v2 session-detail fields
    session_date_label TEXT,
    recipes_summary    JSONB DEFAULT '[]',
    session_start_time TEXT,
    session_end_time   TEXT,
    total_hours        NUMERIC(6,2) DEFAULT 0,
    container_count    INTEGER DEFAULT 0,
    store_trip         BOOLEAN DEFAULT false,
    grocery_total      NUMERIC(12,2) DEFAULT 0,
    service_fee        NUMERIC(12,2) DEFAULT 0,
    -- DI6: soft delete for void invoices
    deleted_at         TIMESTAMPTZ,
    created_at         TIMESTAMPTZ DEFAULT now(),
    updated_at         TIMESTAMPTZ DEFAULT now(),
    UNIQUE (account_id, id),
    UNIQUE (account_id, invoice_number),
    FOREIGN KEY (account_id, client_id) REFERENCES clients(account_id, id),
    FOREIGN KEY (account_id, session_id) REFERENCES sessions(account_id, id)
);

-- Child of invoices.
CREATE TABLE invoice_line_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT REFERENCES invoices(id) ON DELETE CASCADE,
    sort_order  INTEGER DEFAULT 0,
    description TEXT NOT NULL DEFAULT '',
    quantity    NUMERIC(12,3) DEFAULT 1,
    unit_price  NUMERIC(12,2) DEFAULT 0,
    amount      NUMERIC(12,2) DEFAULT 0
);

-- Payment / booking fee log
CREATE TABLE payment_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT NOT NULL REFERENCES accounts(id),
    intake_id       BIGINT,
    -- checkout.session.completed, payment_intent.failed, manual.*, ...
    event_type      TEXT,
    -- NULL for manual events; UNIQUE prevents Stripe duplicate replays
    stripe_event_id TEXT UNIQUE,
    amount          NUMERIC(12,2),
    currency        TEXT DEFAULT 'usd',
    status          TEXT,
    -- full Stripe JSON for audit
    raw_payload     JSONB,
    created_at      TIMESTAMPTZ DEFAULT now(),
    FOREIGN KEY (account_id, intake_id) REFERENCES client_intakes(account_id, id)
);

-- Lookup indexes (DI22 + multitenant account_id indexes)
CREATE INDEX idx_sessions_client           ON sessions(client_id);
CREATE INDEX idx_sessions_date             ON sessions(session_date);
CREATE INDEX idx_session_dishes_session    ON session_dishes(session_id);
CREATE INDEX idx_ingredients_recipe        ON ingredients(recipe_id);
CREATE INDEX idx_invoices_session          ON invoices(session_id);
CREATE INDEX idx_invoices_client           ON invoices(client_id);
CREATE INDEX idx_grocery_session           ON grocery_items(session_id);
CREATE INDEX idx_clients_account           ON clients(account_id);
CREATE INDEX idx_recipes_account           ON recipes(account_id);
CREATE INDEX idx_sessions_account          ON sessions(account_id);
CREATE INDEX idx_session_templates_account ON session_templates(account_id);
CREATE INDEX idx_client_intakes_account    ON client_intakes(account_id);
CREATE INDEX idx_invoices_account          ON invoices(account_id);
CREATE INDEX idx_recipe_import_log_account ON recipe_import_log(account_id);
CREATE INDEX idx_payment_events_account    ON payment_events(account_id);
