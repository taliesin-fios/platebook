-- Single-use sign-up invites for SIGNUP_MODE=invite.
--
-- The server owner creates them with `chef-server invite create`, which
-- prints a link with a random token once; only its SHA-256 is stored. A link
-- works until it is used, revoked or expires. `email`, when set, is the only
-- address that may sign up with it (stored lower-cased).
--
-- Not a tenant table: it is read before any account exists, through the pool
-- (like accounts and used_jtis), and chef_app gets no grant on it. Additive:
-- safe on a live database.
CREATE TABLE signup_invites (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash         TEXT NOT NULL UNIQUE,
    email              TEXT,
    note               TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at         TIMESTAMPTZ NOT NULL,
    used_at            TIMESTAMPTZ,
    used_by_account_id BIGINT REFERENCES accounts(id) ON DELETE SET NULL,
    revoked_at         TIMESTAMPTZ
);
