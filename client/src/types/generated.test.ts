import { describe, expect, it } from 'vitest';

// The generated API types (server-rs, ts-rs) as raw text.
const files = import.meta.glob('./generated/*.ts', { query: '?raw', import: 'default', eager: true }) as Record<string, string>;

describe('generated API types', () => {
  it('exist', () => {
    expect(Object.keys(files).length).toBeGreaterThan(40);
  });

  it('never use bigint (JSON numbers arrive as number; annotate i64 fields with #[ts(type = "number")])', () => {
    const offenders = Object.entries(files).filter(([, src]) => /\bbigint\b/.test(src)).map(([f]) => f);
    expect(offenders).toEqual([]);
  });

  it('are marked as generated', () => {
    for (const src of Object.values(files)) expect(src).toMatch(/generated by \[ts-rs\]/);
  });
});
